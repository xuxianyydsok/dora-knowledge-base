// 模块级单例：只在首次 import 时构造一次
const MAP = new Map(Object.entries(TRADITIONAL_TO_SIMPLIFIED));

/**
 * 繁体转简体。逐字符查表，查不到的原样保留。
 * 非字符串输入原样返回（不抛错），空串返回空串。
 */
export function toSimplified(text) {
  if (typeof text !== 'string' || text.length === 0) return text;
  let out = '';
  let changed = false;
  for (const ch of text) {
    const s = MAP.get(ch);
    if (s === undefined) {
      out += ch;
    } else {
      out += s;
      changed = true;
    }
  }
  // 没发生替换时返回原串，避免大段纯简体歌词白白复制一份
  return changed ? out : text;
}

/** 文本里是否含繁体字（用于决定要不要转，也方便测试）。非字符串返回 false。 */
export function hasTraditional(text) {
  if (typeof text !== 'string' || text.length === 0) return false;
  for (const ch of text) {
    if (MAP.has(ch)) return true;
  }
  return false;
}

